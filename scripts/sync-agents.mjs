#!/usr/bin/env node
//
// sync-agents.mjs
//
// Generates the GitHub Copilot CLI copies of the subagents.
//
//   Source:  .claude/agents/<name>.md          (edit only here)
//   Copy:    .github/agents/<name>.agent.md    (generated, never edit by hand)
//
// Why: Copilot CLI loads both folders, and on a name clash the
// .github/agents/ copy wins. Claude-only frontmatter (e.g. `model: sonnet`)
// makes Copilot refuse to start the agent, so the copy drops it and maps the
// tool names to Copilot's aliases. The body stays 1:1.
//
// Usage:
//   node scripts/sync-agents.mjs           write/refresh/remove the copies
//   node scripts/sync-agents.mjs --check   change nothing; exit 1 if a copy is stale
//   node scripts/sync-agents.mjs --hook    for the tool hooks (.claude/settings.json,
//                                          .github/hooks/sync-agents.json): sync only
//                                          if the tool call on stdin touched .claude/agents/
//
// Only files carrying the GENERATED marker are touched or removed. A hand-made
// .github/agents/*.agent.md without the marker stays as it is.

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(ROOT, '.claude', 'agents');
const OUT_DIR = join(ROOT, '.github', 'agents');
const MARKER = '# GENERATED by scripts/sync-agents.mjs';

// Claude Code tool name -> Copilot CLI tool alias.
const TOOL_MAP = {
  Read: 'read',
  Glob: 'search',
  Grep: 'search',
  Write: 'edit',
  Edit: 'edit',
  MultiEdit: 'edit',
  NotebookEdit: 'edit',
  Bash: 'execute',
  WebFetch: 'web',
  WebSearch: 'web',
  Agent: 'agent',
  Task: 'agent',
  TodoWrite: 'todo',
};

// Claude-only frontmatter keys. Copilot CLI does not know them; `model` with a
// Claude alias even stops the agent from starting.
const DROP_KEYS = new Set([
  'model', 'permissionMode', 'color', 'memory', 'maxTurns', 'effort',
  'isolation', 'background', 'initialPrompt', 'hooks', 'skills',
]);

const check = process.argv.includes('--check');
const hook = process.argv.includes('--hook');

// --hook: called by the Claude Code / Copilot CLI hook after every tool use,
// with the tool call as JSON on stdin. Sync only when the call touched
// .claude/agents/. Never fail the tool call: errors go to stderr, exit 0.
if (hook) {
  let input = '';
  try { input = readFileSync(0, 'utf8'); } catch { /* no stdin */ }
  if (!/\.claude(\\|\/)+agents(\\|\/)/.test(input)) process.exit(0); // / or \ (JSON-escaped)
}

function fail(msg) {
  console.error(`sync-agents: ${msg}`);
  process.exit(hook ? 0 : 2);
}

function parseToolList(text) {
  return text.replace(/^\[|\]$/g, '').split(',').map((t) => t.trim()).filter(Boolean);
}

function mapTools(tools, file) {
  const out = [];
  for (const tool of tools) {
    const mapped = TOOL_MAP[tool];
    if (!mapped) fail(`${file}: unknown tool "${tool}". Add it to TOOL_MAP in scripts/sync-agents.mjs.`);
    if (!out.includes(mapped)) out.push(mapped);
  }
  return out;
}

function convert(source, file) {
  const lines = source.replace(/\r\n/g, '\n').split('\n');
  if (lines[0] !== '---') fail(`${file}: no frontmatter.`);
  const end = lines.indexOf('---', 1);
  if (end === -1) fail(`${file}: frontmatter not closed.`);

  const front = [MARKER + ' from .claude/agents/' + file + ' -- do not edit by hand.'];
  let i = 1;
  while (i < end) {
    const line = lines[i];
    const key = /^([A-Za-z][A-Za-z0-9_-]*):/.exec(line)?.[1];

    if (key === 'tools') {
      // Inline list ("tools: Read, Grep") or YAML block list ("tools:" + "  - Read").
      const tools = parseToolList(line.slice('tools:'.length));
      i++;
      while (i < end && /^\s+-\s/.test(lines[i])) {
        tools.push(lines[i].replace(/^\s+-\s+/, '').trim());
        i++;
      }
      front.push('tools:', ...mapTools(tools, file).map((t) => `  - ${t}`));
      continue;
    }
    if (key && DROP_KEYS.has(key)) {
      i++;
      while (i < end && /^\s/.test(lines[i])) i++; // drop nested values too
      continue;
    }
    front.push(line);
    i++;
  }
  return ['---', ...front, ...lines.slice(end)].join('\n');
}

if (!existsSync(SRC_DIR)) fail('.claude/agents/ not found.');
if (!check) mkdirSync(OUT_DIR, { recursive: true });

const sources = readdirSync(SRC_DIR).filter((f) => f.endsWith('.md')).sort();
const wanted = new Set();
const stale = [];

for (const file of sources) {
  const name = file.replace(/\.md$/, '');
  const outName = `${name}.agent.md`;
  const outPath = join(OUT_DIR, outName);
  wanted.add(outName);

  const expected = convert(readFileSync(join(SRC_DIR, file), 'utf8'), file);
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;

  if (current !== null && !current.includes(MARKER)) {
    fail(`.github/agents/${outName} exists but was not generated. Remove it or rename the agent in .claude/agents/.`);
  }
  if (current === expected) continue;

  stale.push(`.github/agents/${outName} ${current === null ? 'missing' : 'outdated'}`);
  if (!check) writeFileSync(outPath, expected);
}

if (existsSync(OUT_DIR)) {
  for (const file of readdirSync(OUT_DIR)) {
    if (wanted.has(file) || !file.endsWith('.agent.md')) continue;
    const path = join(OUT_DIR, file);
    if (!readFileSync(path, 'utf8').includes(MARKER)) continue; // hand-made, leave it
    stale.push(`.github/agents/${file} orphaned (no .claude/agents/ source)`);
    if (!check) unlinkSync(path);
  }
}

if (check) {
  if (stale.length) {
    console.error('Copilot agent copies are out of date:');
    for (const s of stale) console.error(`  - ${s}`);
    console.error('Fix: run `node scripts/sync-agents.mjs` and commit .github/agents/.');
    process.exit(1);
  }
  console.log(`sync-agents: ${sources.length} agents in sync.`);
} else {
  console.log(stale.length
    ? `sync-agents: updated ${stale.length} file(s):\n  ${stale.join('\n  ')}`
    : `sync-agents: ${sources.length} agents already in sync.`);
}
